/**
 * SAUCE's melody presets (MELODY: OFF · FOLLOW · FIT). A preset is an 8-note phrase of scale degrees (0 = the root an
 * octave below the instrument's, the ladder's bottom; the design's SEQUENCE strip shows it) with a chord for each step:
 * FOLLOW plays the next degree on each pluck, FIT snaps the hand's note to the step's chord tones; each pluck advances,
 * wrapping at the end. Degrees, so a key or scale change transposes it. Rule-based and original: the design's four
 * (Night hook, Kitsune, Low rider, Lantern) and Rolled, built by roll() from seeded rules (a 4-note motif and its answer
 * coming home): never copied, never generated by a model.
 */
export type MelodyMode = 'off' | 'follow' | 'fit'

export interface MelodyPreset {
  id: string
  name: string
  /** The phrase: scale degrees from the ladder's bottom. */
  steps: number[]
  /** Each step's chord: the degrees (any octave) FIT allows. */
  chords: number[][]
}

const triad = (r: number) => [r, r + 2, r + 4]
const hold = (chord: number[], n: number) => Array.from({ length: n }, () => chord)

/** The design's four (its SEQUENCE strip's notes), each half on the chord its notes sit in. */
export const PRESETS: readonly MelodyPreset[] = [
  { id: 'night-hook', name: 'Night hook', steps: [4, 6, 7, 6, 4, 3, 4, 1], chords: [...hold(triad(2), 4), ...hold(triad(4), 4)] },
  { id: 'kitsune', name: 'Kitsune', steps: [2, 4, 5, 7, 9, 7, 5, 4], chords: hold(triad(0), 8) },
  { id: 'low-rider', name: 'Low rider', steps: [0, 0, 2, 3, 0, 4, 3, 2], chords: [...hold(triad(3), 4), ...hold(triad(0), 4)] },
  { id: 'lantern', name: 'Lantern', steps: [5, 7, 8, 7, 5, 4, 2, 4], chords: [...hold(triad(3), 4), ...hold(triad(0), 4)] },
]

/** mulberry32: a small seeded generator (the same seed, the same melody). */
function seeded(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** A new 8-note melody (Rolled) for a scale of `scaleLen` notes: a 4-note motif (mostly stepwise, a leap now and then)
 *  and its answer (the contour turned over) ending on the root or its octave; each half on a chord of a common
 *  progression. Within the ladder (0 … 1.5 octaves). */
export function roll(seed: number, scaleLen = 5): MelodyPreset {
  const rnd = seeded(seed)
  const top = Math.round(1.5 * scaleLen)
  const pick = <T>(xs: readonly T[]) => xs[Math.floor(rnd() * xs.length)]!
  const clamp = (d: number) => Math.max(0, Math.min(top, d))
  const len = 4
  const motif: number[] = []
  let d = 2 + Math.floor(rnd() * 3)
  for (let i = 0; i < len; i++) {
    motif.push(d)
    d = clamp(d + pick([-2, -1, -1, 0, 1, 1, 2, 3, -3]))
  }
  const answer = motif.map((x) => clamp(2 * motif[0]! - x)) // the contour turned over round its first note
  answer[answer.length - 1] = rnd() < 0.5 ? 0 : Math.min(top, scaleLen) // home: the root, or its octave
  const steps = [...motif, ...answer]
  const roots = pick([[3, 0], [2, 0], [4, 0], [1, 0]]).map((r) => r % scaleLen) // away, then home
  const chords = steps.map((_, i) => triad(roots[i < len ? 0 : 1]!))
  return { id: 'rolled', name: 'Rolled', steps, chords }
}

/** The nearest degree to `deg` on a ladder of `size` steps that `chord` allows (any octave of its tones); ties go up. */
export function snapToChord(deg: number, chord: readonly number[], scaleLen: number, size: number): number {
  const ok = new Set(chord.map((c) => ((c % scaleLen) + scaleLen) % scaleLen))
  for (let r = 0; r < size; r++) for (const c of [deg + r, deg - r]) if (c >= 0 && c < size && ok.has(c % scaleLen)) return c
  return deg
}

/** A melody's place: FOLLOW's next note, FIT's allowed notes, advancing on each pluck and wrapping. */
export function createMelody(preset: MelodyPreset = PRESETS[0]!) {
  let p = preset
  let pos = 0
  let wrapped = false
  return {
    get preset() { return p },
    get position() { return pos },
    get length() { return p.steps.length },
    /** True once, just after the phrase came round to the top ("↺ from the top" in the trail). */
    get wrapped() { return wrapped },
    set(next: MelodyPreset) {
      p = next
      pos = 0
      wrapped = false
    },
    reset() {
      pos = 0
      wrapped = false
    },
    /** FOLLOW: the next degree. */
    next: () => p.steps[pos]!,
    /** FIT: the chord the current step allows. */
    chord: () => p.chords[pos] ?? p.chords[0]!,
    advance() {
      pos = (pos + 1) % p.steps.length
      wrapped = pos === 0
    },
  }
}
export type Melody = ReturnType<typeof createMelody>
